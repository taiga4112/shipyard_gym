"""Regenerate the README's scene section from ``configs/scenes/*.yaml``.

    uv run python -m ortsim.tools.scene_docs        # rewrite README.md in place
    uv run python -m ortsim.tools.scene_docs --check  # exit 1 if README is stale (CI)

The section sits between ``<!-- scenes:begin -->`` and ``<!-- scenes:end -->``; the
configs are the source of truth (``description`` per scene, ``notes`` per set).
"""

from __future__ import annotations

import argparse
import sys

from .. import REPO_ROOT
from ..config import CONFIG_DIR
from ..yamlio import load_yaml

BEGIN, END = "<!-- scenes:begin -->", "<!-- scenes:end -->"


def render() -> str:
    out = [BEGIN, "", "<!-- generated by `uv run python -m ortsim.tools.scene_docs`; edit configs/scenes/*.yaml -->", ""]
    out += ["| シーン | 内容 |", "|---|---|", "| `builtin/flat` | 平地（無限平面） |", ""]
    for path in sorted((CONFIG_DIR / "scenes").glob("*.yaml")):
        raw = load_yaml(path)
        name = raw.get("name", path.stem)
        out.append(f"#### `{name}/*` — {raw.get('description', '')}".rstrip(" —"))
        out.append("")
        for note in raw.get("notes", []) or []:
            out.append(f"- {note}")
        if raw.get("notes"):
            out.append("")
        out += ["| シーン | 内容 |", "|---|---|"]
        for key, entry in raw["scenes"].items():
            out.append(f"| `{name}/{key}` | {(entry or {}).get('description', '')} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that README.md is up to date")
    args = ap.parse_args(argv)
    readme = REPO_ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        sys.exit(f"README.md has no {BEGIN} ... {END} section")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + render() + tail
    if args.check:
        if new != text:
            sys.exit("README.md scene section is stale: run `uv run python -m ortsim.tools.scene_docs`")
        print("README.md scene section is up to date")
        return
    readme.write_text(new, encoding="utf-8")
    print("updated README.md scene section")


if __name__ == "__main__":
    main()
